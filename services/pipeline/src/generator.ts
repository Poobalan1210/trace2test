import type { Bundle } from '@t2t/shared';
import { REPLAY_HEADERS } from './config.js';

/**
 * Builds the Jest regression test from a fixed template. No model is involved:
 * the same bundle always yields the same file, byte for byte. Every captured
 * value enters the code through JSON.stringify, and every captured value that
 * appears in a comment goes through commentSafe, so nothing can break out.
 */

export interface TestInput {
  bundle: Bundle;
  /** Staging's status on replay; undefined when the request was not replayed. */
  stagingStatus?: number;
}

export function pathSlug(path: string): string {
  const slug = path.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40).replace(/-+$/, '');
  return slug || 'root';
}

export function testFilename(bundle: Pick<Bundle, 'request' | 'response' | 'fingerprint'>): string {
  return `${pathSlug(bundle.request.path)}-${bundle.response.status}-${bundle.fingerprint.slice(0, 6)}.test.js`;
}

/** Comment text: one line, printable, and unable to close the comment. */
export function commentSafe(text: string, max = 120): string {
  // eslint-disable-next-line no-control-regex
  const flat = String(text).replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, ' ').replace(/\*\//g, '* /').trim();
  return flat.length > max ? flat.slice(0, max - 1) + '…' : flat;
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const literalKey = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));
const isPlain = (v: unknown) => v === null || typeof v !== 'object';

/**
 * Renders a JSON value as a readable JavaScript literal. Objects and arrays
 * holding only primitives go on one line when short; anything else is spread
 * over several lines. Strings and numbers are always JSON.stringify output.
 */
export function literal(value: unknown, indent = ''): string {
  if (value === undefined) return 'undefined';
  if (isPlain(value)) return JSON.stringify(value);
  const inner = indent + '  ';
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    if (value.every(isPlain)) {
      const one = `[${value.map((v) => JSON.stringify(v)).join(', ')}]`;
      if (one.length + indent.length <= 80) return one;
    }
    return `[\n${value.map((v) => inner + literal(v, inner)).join(',\n')}\n${indent}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  if (entries.length === 0) return '{}';
  if (entries.every(([, v]) => isPlain(v))) {
    const one = `{ ${entries.map(([k, v]) => `${literalKey(k)}: ${JSON.stringify(v)}`).join(', ')} }`;
    if (one.length + indent.length <= 80) return one;
  }
  return `{\n${entries.map(([k, v]) => `${inner}${literalKey(k)}: ${literal(v, inner)}`).join(',\n')}\n${indent}}`;
}

const BODYLESS = new Set(['GET', 'HEAD']);

export function generateTest({ bundle, stagingStatus }: TestInput): { filename: string; source: string } {
  const filename = testFilename(bundle);
  const fp6 = bundle.fingerprint.slice(0, 6);
  const req = bundle.request;
  const hasBody = !BODYLESS.has(req.method) && req.body !== null && req.body !== undefined;
  const hasQuery = Object.keys(req.query).length > 0;
  const redacted = [...new Set(bundle.redactions.map((r) => r.path))];
  const capturedAt = bundle.capturedAt.replace(/\.\d+Z$/, 'Z');
  // Same headers the Replay step sends; the API key comes from the environment instead.
  const headers = Object.fromEntries(Object.entries(req.headers).filter(([k]) => REPLAY_HEADERS.includes(k.toLowerCase())));

  const requestFields = [
    `  method: ${JSON.stringify(req.method)}`,
    `  path: ${JSON.stringify(req.path)}`,
    ...(hasQuery ? [`  query: ${literal(req.query, '  ')}`] : []),
    `  headers: ${literal(headers, '  ')}`,
    ...(hasBody ? [`  body: ${literal(req.body, '  ')}`] : []),
  ];

  const url = hasQuery
    ? 'TARGET + request.path + "?" + new URLSearchParams(request.query)'
    : 'TARGET + request.path';

  const lines = [
    '/**',
    ' * Regression test generated by Trace2Test',
    ' *',
    ` * Incident:    ${commentSafe(bundle.incidentId)}`,
    ` * Captured:    ${commentSafe(capturedAt)} from ${commentSafe(bundle.service)} (production)`,
    ` * Request:     ${commentSafe(`${req.method} ${req.path}`)}`,
    ` * Production:  ${commentSafe(`${bundle.response.status} ${bundle.error.name}: ${bundle.error.message}`)}`,
    stagingStatus === undefined
      ? ' * Staging:     not replayed; run this test to confirm the failure'
      : ` * Staging:     reproduced (${stagingStatus}, same error signature)`,
    ...(redacted.length ? [` * Redacted:    ${commentSafe(redacted.join(', '), 400)}`] : []),
    ' *',
    ' * Run against staging or a local server:',
    ' *   T2T_TARGET_URL=https://<staging-host> T2T_TARGET_API_KEY=<key> \\',
    ` *     npx jest ${filename}`,
    ' *',
    ' * This test fails while the bug exists and passes once it is fixed.',
    ' * It is skipped when T2T_TARGET_URL is not set.',
    ' */',
    '',
    'const TARGET = (process.env.T2T_TARGET_URL || "").replace(/\\/+$/, "");',
    'const API_KEY = process.env.T2T_TARGET_API_KEY;',
    '',
    'const request = {',
    requestFields.join(',\n'),
    '};',
    '',
    '// Skipped rather than failed without a target, so the file can live in any suite.',
    `(TARGET ? describe : describe.skip)(${JSON.stringify(`${req.method} ${req.path} (incident ${fp6})`)}, () => {`,
    '  test("does not fail with a server error", async () => {',
    `    const res = await fetch(${url}, {`,
    '      method: request.method,',
    '      headers: { ...request.headers, ...(API_KEY ? { "x-api-key": API_KEY } : {}) }' + (hasBody ? ',' : ''),
    ...(hasBody ? ['      body: JSON.stringify(request.body)'] : []),
    '    });',
    '    const text = await res.text();',
    '',
    `    // Captured in production: ${bundle.response.status}. A fixed server must not return 5xx here.`,
    '    if (res.status >= 500) console.error(text);',
    '    expect(res.status).toBeLessThan(500);',
    '  });',
    '',
    '  // Tighten this once you know the intended behaviour, for example:',
    '  // expect(res.status).toBe(200);',
    '});',
    '',
  ];
  return { filename, source: lines.join('\n') };
}
